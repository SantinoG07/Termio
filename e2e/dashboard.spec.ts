import { test, expect } from '@playwright/test'

test('dashboard demo, navegación, filtros, detalle y exportación', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Vista general' })).toBeVisible()
  await expect(page.locator('.node-card')).toHaveCount(6)
  await page.screenshot({ path: 'qa/dashboard-desktop.png', fullPage: true })
  await page.locator('.node-card').first().getByRole('button', { name: 'Ver registro' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByText('record_id', { exact: false })).toBeVisible()
  await page.screenshot({ path: 'qa/record-dialog.png', fullPage: true })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Registros' }).click()
  await expect(page).toHaveURL(/\/records$/)
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.getByLabel('Buscar nodos o registros').fill('water_node')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar JSON' }).click()
  expect((await download).suggestedFilename()).toBe('termio-test-registros.json')
  await page.getByLabel('Buscar nodos o registros').fill('')
  await page.keyboard.press('Control+Alt+Shift+D')
  await expect(page.getByRole('dialog', { name: 'Panel técnico' })).toBeVisible()
  await page.getByLabel('Entorno de datos').selectOption('operational')
  await page.getByRole('button', { name: 'Cerrar panel técnico' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(6)
  await page.keyboard.press('Control+Alt+Shift+D')
  await page.getByLabel('Entorno de datos').selectOption('test')
  await page.getByRole('button', { name: 'Cerrar panel técnico' }).click()
  await page.getByRole('navigation').getByRole('link', { name: /Alertas/ }).click()
  await expect(page.locator('.alert-card')).toHaveCount(1)
  await page.screenshot({ path: 'qa/alerts-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

